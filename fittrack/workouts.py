"""תוכניות אימון מוכנות למתחילים ולאנשים עם ניסיון קצר.

התוכנית נבחרת לפי המטרה, הניסיון ומספר הימים.
אין כאן עומסים אישיים: המתאמן בוחר משקל שמאפשר לשמור על טכניקה.
"""

GOAL_REPS = {
    "fat_loss": "10–15",
    "muscle_gain": "6–10",
    "maintain": "8–12",
    "general": "8–12",
}

GOAL_REST = {
    "fat_loss": "כ-60–90 שניות מנוחה בין הסטים.",
    "muscle_gain": "כ-90–150 שניות מנוחה בין הסטים.",
    "maintain": "כ-90 שניות מנוחה בין הסטים.",
    "general": "כ-90 שניות מנוחה בין הסטים.",
}


def _sets(experience):
    if experience == "intermediate":
        return 4
    return 3


def _move(name, sets, reps, tip):
    return {"name": name, "sets": sets, "reps": reps, "tip": tip}


def _strength_day(title, focus, moves, experience, goal):
    """הופך רשימת תרגילים ליום אימון, עם טווח חזרות לפי המטרה."""
    sets = _sets(experience)
    reps = GOAL_REPS[goal]
    exercises = []
    for name, tip, special_reps in moves:
        exercises.append(_move(name, sets, special_reps or reps, tip))
    return {"title": title, "focus": focus, "exercises": exercises}


def build_plan(goal, experience, training_days):
    """מחזיר תוכנית שבועית ורשימת דגשים קצרים."""
    days = int(training_days)
    if days <= 2:
        plan = _two_days(experience, goal)
    elif days == 3:
        plan = _three_days(experience, goal)
    elif days == 4:
        plan = _four_days(experience, goal)
    else:
        plan = _five_days(experience, goal)

    notes = [
        "לפני כל אימון: 5 דקות הליכה או אופניים קלים, ואז סט אחד קל של התרגיל הראשון.",
        "בוחרים משקל שאפשר לסיים איתו את כל החזרות בצורה נקייה. אם הטכניקה נשברת, מפחיתים משקל.",
        "כאב חד במפרק, בסרב או בחזה הוא סיבה לעצור. מאמץ בשריר בזמן העבודה הוא תחושה אחרת.",
        GOAL_REST[goal],
    ]
    if experience == "beginner" and days >= 5:
        notes.append("למתחילים, גם 3 ימי אימון בשבוע יכולים להספיק. חמישה ימים דורשים יותר התאוששות.")
    if goal == "fat_loss":
        notes.append("לירידה במשקל כדאי להוסיף הליכה ברוב ימות השבוע. האימון שומר על השריר, וההליכה מוסיפה תנועה.")
    if goal == "muscle_gain":
        notes.append("בעלייה במסת שריר ההתקדמות מגיעה כשאפשר, לאט, להוסיף חזרה או מעט משקל בלי לאבד טכניקה.")

    return {"days": plan, "notes": notes}


